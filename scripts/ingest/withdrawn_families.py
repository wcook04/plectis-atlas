#!/usr/bin/env python3
"""Record which family each withdrawn manuscript belonged to on the day of the release.

    python3 scripts/ingest/withdrawn_families.py [UPSTREAM_CHECKOUT]   (default ../openai-math-upstream)

Withdrawn manuscripts leave the release's CONTENTS.md, so at the pinned commit they have no
family. The release's first commit (adc7f124, 6 October 2026) still lists them under their
family. This reads CONTENTS.md at that commit from the upstream checkout's history with the
atlas's own parser, and writes curated/withdrawn_families.json for the manuscripts that are
withdrawn at the pin. scripts/build_data.py gives each its release-day family and says so.
Standard library only.
"""
from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
import build_data as bd  # noqa: E402

RELEASE_COMMIT = "adc7f1241b42e322a6451854ab7e4b4c146bf78a"


def main() -> int:
    upstream = Path(sys.argv[1]) if len(sys.argv) > 1 else (ROOT / ".." / "openai-math-upstream").resolve()
    r = subprocess.run(["git", "-C", str(upstream), "show", f"{RELEASE_COMMIT}:CONTENTS.md"],
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"cannot read CONTENTS.md at {RELEASE_COMMIT[:8]}: {r.stderr.strip()}")
    with tempfile.TemporaryDirectory() as d:
        p = Path(d) / "CONTENTS.md"
        p.write_text(r.stdout, encoding="utf-8")
        day_one = bd.parse_contents(p)
    family_of = {m["slug"]: (fid, f["title"]) for fid, f in day_one.items() for m in f["manuscripts"] if m["slug"]}
    manuscripts = json.loads((ROOT / "data" / "manuscripts.json").read_text(encoding="utf-8"))
    out = {}
    for m in manuscripts:
        if m["status"] != "withdrawn":
            continue
        hit = family_of.get(m["id"])
        if hit:
            out[m["id"]] = {"family": hit[0], "family_title_then": hit[1]}
        else:
            print(f"not listed on release day: {m['id']}")
    doc = {
        "_note": ("Generated by scripts/ingest/withdrawn_families.py: the family under which the release's "
                  "CONTENTS.md listed each now-withdrawn manuscript at the release's first commit."),
        "release_commit": RELEASE_COMMIT,
        "source": f"https://github.com/openai/math/blob/{RELEASE_COMMIT}/CONTENTS.md",
        "manuscripts": out,
    }
    dest = ROOT / "curated" / "withdrawn_families.json"
    dest.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {dest.relative_to(ROOT)}: {len(out)} withdrawn manuscripts with a release-day family")
    return 0


if __name__ == "__main__":
    sys.exit(main())
